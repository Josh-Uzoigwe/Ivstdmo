async function main() {
  console.log("Seeding Northstone database...");

  // 1. Upsert all assets
  for (const a of SEED_ASSETS) {
    const high52wCents = Math.round(a.basePriceCents * (1 + a.volatility * 6));
    const low52wCents = Math.max(10, Math.round(a.basePriceCents * (1 - a.volatility * 5)));
    await prisma.asset.upsert({
      where: { ticker: a.ticker },
      update: {
        name: a.name,
        assetClass: a.assetClass,
        exchange: a.exchange,
        currency: a.currency,
        sector: a.sector,
        description: a.description,
        marketCapCents: a.marketCapCents,
        peRatio: a.peRatio,
        dividendYield: a.dividendYield,
        high52wCents,
        low52wCents,
        basePriceCents: a.basePriceCents,
        volatility: a.volatility,
      },
      create: {
        ticker: a.ticker,
        name: a.name,
        assetClass: a.assetClass,
        exchange: a.exchange,
        currency: a.currency,
        sector: a.sector,
        description: a.description,
        marketCapCents: a.marketCapCents,
        peRatio: a.peRatio,
        dividendYield: a.dividendYield,
        high52wCents,
        low52wCents,
        basePriceCents: a.basePriceCents,
        volatility: a.volatility,
      },
    });
  }
  console.log(`Seeded ${SEED_ASSETS.length} assets.`);

  // 2. Ensure MarketSimState singleton exists
  await prisma.marketSimState.upsert({
    where: { id: "singleton" },
    update: {},
    create: {
      id: "singleton",
      isPaused: false,
      volatilityMultiplier: 1.0,
      tickSeedOffset: 0,
    },
  });

  // 3. Seed ONLY the single Admin account from env vars (user accounts remain empty for open signup)
  const adminEmail = process.env.ADMIN_EMAIL || "admin@northstone-demo.example";
  const adminPassword = process.env.ADMIN_PASSWORD || "AdminDemo!2026";
  const passwordHash = await bcrypt.hash(adminPassword, 10);

  const admin = await prisma.user.upsert({
    where: { email: adminEmail },
    update: {},
    create: {
      email: adminEmail,
      passwordHash,
      name: "Platform Administrator",
      role: "ADMIN",
      baseCurrency: "USD",
      referralCode: "NS-ADMIN",
      kycProfile: {
        create: {
          status: "APPROVED",
          fullName: "Platform Administrator",
          agreementsAccepted: true,
          riskTolerance: "MODERATE",
          riskScore: 60,
          submittedAt: new Date(),
          reviewedAt: new Date(),
        },
      },
      cashBalances: {
        create: [
          { currency: "USD", amountCents: 0 },
          { currency: "EUR", amountCents: 0 },
          { currency: "GBP", amountCents: 0 },
        ],
      },
    },
  });

  console.log(`Seeded admin account: ${admin.email}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
